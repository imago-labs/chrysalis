# Audit Record
# ---------------------------------------------------------------------------

class AuditRecord(BaseModel):
    """
    Immutable log entry for every memory operation.

    Written once, never modified. Queryable by session, tag, time, or key.
    This is the SAF continuous observability layer made concrete.
    """
    model_config = ConfigDict(
        str_strip_whitespace=True,
        validate_assignment=True,
        extra="forbid",
    )

    audit_id: str = Field(
        default_factory=lambda: str(uuid.uuid4()),
        description="Unique audit record identifier"
    )
    entry_id: str = Field(
        ...,
        description="MemoryEntry this record corresponds to"
    )
    session_id: str = Field(..., description="Originating session")
    key: str = Field(..., description="Memory key operated on")
    content: Optional[str] = Field(default=None, description="Belief content text")

    operation: str = Field(
        ...,
        description="Operation type: WRITE_APPROVED, WRITE_FLAGGED, WRITE_REJECTED, READ, STALE_DETECTED"
    )

    epistemic_tag: EpistemicTag = Field(..., description="Final tag assigned")
    critique_verdict: CritiqueVerdict = Field(..., description="Critique outcome")
    critique_notes: Optional[str] = Field(default=None)

    source_reference: Optional[str] = Field(default=None)
    tool_call_id: Optional[str] = Field(default=None)
    human_session_context: Optional[str] = Field(default=None)

    recorded_at: datetime = Field(
        default_factory=lambda: datetime.now(timezone.utc),
        description="When this audit record was written"
    )

    metadata: Dict[str, Any] = Field(
        default_factory=dict,
        description="Additional structured metadata (latency, model used, token count, etc.)"
    )


