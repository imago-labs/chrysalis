"""
MEMOIR Core Data Models
-----------------------
MemoryEntry, EpistemicTag, AuditRecord, DriftReport

These models are the schema contract for the entire system.
Everything flows through here.
"""

from __future__ import annotations

import uuid
from datetime import datetime, timezone
from enum import Enum
from typing import Any, Dict, List, Optional

from pydantic import BaseModel, Field, ConfigDict, field_validator


# ---------------------------------------------------------------------------
# Epistemic Classification
# ---------------------------------------------------------------------------

class EpistemicTag(str, Enum):
    """
    Confidence classification for every memory entry.

    VERIFIED              -- checked against source and confirmed
    USER_STATED           -- direct claim or instruction from the user
    INFERRED              -- derived from verified memories via reasoning
    ASSUMED               -- agent-generated without verification
    STALE                 -- previously verified but TTL exceeded
    REJECTED              -- failed critique; not written
    AGENT_DERIVED         -- conclusions the agent reached through analysis
    METACOGNITIVE_INSIGHT -- generated by ORACLE self-reflection loop
    """
    VERIFIED = "VERIFIED"
    USER_STATED = "USER_STATED"
    INFERRED = "INFERRED"
    ASSUMED  = "ASSUMED"
    STALE    = "STALE"
    REJECTED = "REJECTED"
    AGENT_DERIVED = "AGENT_DERIVED"
    METACOGNITIVE_INSIGHT = "METACOGNITIVE_INSIGHT"


class CritiqueVerdict(str, Enum):
    """Outcome of the secondary critique agent pass."""
    PASS     = "PASS"      # Write approved
    FLAG     = "FLAG"      # Write approved with warning attached
    REJECT   = "REJECT"    # Write blocked


# ---------------------------------------------------------------------------
# Memory Entry
# ---------------------------------------------------------------------------

class MemoryEntry(BaseModel):
    """
    A single memory unit proposed for storage.

    This is the object that enters MEMOIR's validation pipeline.
    On exit it carries its epistemic tag, critique verdict, and audit ID.
    """
    model_config = ConfigDict(
        str_strip_whitespace=True,
        validate_assignment=True,
        extra="forbid",
    )

    # Identity
    entry_id: str = Field(
        default_factory=lambda: str(uuid.uuid4()),
        description="Unique identifier for this memory entry"
    )
    session_id: str = Field(
        ...,
        description="Session that generated this entry (e.g., Claude Code session ID)",
        min_length=1,
    )
    agent_id: Optional[str] = Field(
        default=None,
        description="Sub-agent identifier if generated by a worker agent"
    )

    # Content
    key: str = Field(
        ...,
        description="Memory key (maps to MEMORY.md pointer index)",
        min_length=1,
        max_length=200,
    )
    content: str = Field(
        ...,
        description="The belief or fact the agent wants to record",
        min_length=1,
        max_length=4000,
    )
    source_reference: Optional[str] = Field(
        default=None,
        description="File path, URL, or document reference the agent claims this derives from"
    )

    # Provenance
    tool_call_id: Optional[str] = Field(
        default=None,
        description="Tool call that produced this memory entry"
    )
    triggering_input: Optional[str] = Field(
        default=None,
        description="The agent input that led to this memory write (truncated)"
    )
    human_session_context: Optional[str] = Field(
        default=None,
        description="Human authorization context: who was present, what they requested"
    )

    # Timestamps
    proposed_at: datetime = Field(
        default_factory=lambda: datetime.now(timezone.utc),
        description="When the agent proposed this write"
    )

    # Classification (populated by MEMOIR pipeline)
    epistemic_tag: Optional[EpistemicTag] = Field(
        default=None,
        description="Confidence classification assigned by MEMOIR classifier"
    )
    critique_verdict: Optional[CritiqueVerdict] = Field(
        default=None,
        description="Outcome of secondary critique agent pass"
    )
    critique_notes: Optional[str] = Field(
        default=None,
        description="Critique agent reasoning and any flagged contradictions"
    )
    verified_at: Optional[datetime] = Field(
        default=None,
        description="When ground truth verification was performed (VERIFIED entries only)"
    )
    stale_after: Optional[datetime] = Field(
        default=None,
        description="Datetime after which this entry should be reclassified as STALE"
    )

    @field_validator("content")
    @classmethod
    def content_not_empty(cls, v: str) -> str:
        if not v.strip():
            raise ValueError("Memory content cannot be empty or whitespace only")
        return v


