class MetacognitiveInsight(BaseModel):
    """
    A single insight generated by ORACLE's self-reflection loop.
    These get written back as METACOGNITIVE_INSIGHT belief types.
    """
    model_config = ConfigDict(extra="forbid")

    insight_id: str = Field(default_factory=lambda: str(uuid.uuid4()))
    session_id: str
    cycle_id: str
    category: str = Field(description="e.g. 'recurring_rejection', 'source_degradation', 'calibration_drift'")
    description: str
    severity: str = Field(description="LOW, MEDIUM, HIGH")
    affected_entries: List[str] = Field(default_factory=list)
    recommendation: str
    generated_at: datetime = Field(default_factory=lambda: datetime.now(timezone.utc))


class OracleReport(BaseModel):
    """
    Full output of an ORACLE analysis cycle for a session.
    Contains BQS scores, pattern analysis, and generated insights.
    """
    model_config = ConfigDict(extra="forbid")

    report_id: str = Field(default_factory=lambda: str(uuid.uuid4()))
    session_id: str
    cycle_id: str
    audit_range_start: datetime
    audit_range_end: datetime
    total_entries_analyzed: int = Field(ge=0)
    bqs_scores: List[BQSScore] = Field(default_factory=list)
    avg_bqs: float = Field(ge=0.0, le=1.0, default=0.0)
    insights: List[MetacognitiveInsight] = Field(default_factory=list)
    source_weight_updates: Dict[str, float] = Field(default_factory=dict)
    generated_at: datetime = Field(default_factory=lambda: datetime.now(timezone.utc))
