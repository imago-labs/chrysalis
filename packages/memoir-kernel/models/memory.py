class DriftEvent(BaseModel):
    """A single detected divergence between memory and ground truth."""
    key: str
    memory_content: str
    actual_content: str
    drift_type: str  # CONTRADICTION, STALE, MISSING_SOURCE
    severity: str    # LOW, MEDIUM, HIGH
    detected_at: datetime = Field(default_factory=lambda: datetime.now(timezone.utc))


class DriftReport(BaseModel):
    """
    Behavioral drift report for a session or time window.

    Compares current memory state against actual source material.
    Surfaces the gap between what the agent believes and what is true.
    """
    model_config = ConfigDict(extra="forbid")

    report_id: str = Field(default_factory=lambda: str(uuid.uuid4()))
    session_id: Optional[str] = Field(default=None, description="Session scoped to, or None for global")
    window_start: datetime
    window_end: datetime

    total_entries_checked: int = Field(ge=0)
    drift_events: List[DriftEvent] = Field(default_factory=list)
    drift_rate: float = Field(ge=0.0, le=1.0, description="Fraction of entries with detected drift")

    stale_count: int = Field(default=0, ge=0)
    contradiction_count: int = Field(default=0, ge=0)
    missing_source_count: int = Field(default=0, ge=0)

    generated_at: datetime = Field(default_factory=lambda: datetime.now(timezone.utc))
    summary: Optional[str] = Field(default=None, description="Human-readable drift summary")


