# ---------------------------------------------------------------------------
# BQS (Belief Quality Score) Model
# ---------------------------------------------------------------------------

class BQSScore(BaseModel):
    """
    Belief Quality Score computed by the ORACLE engine.
    Five dimensions, each 0.0-1.0, weighted into a composite score.
    I chose these weights based on what matters most for epistemic trust.
    """
    model_config = ConfigDict(extra="forbid")

    entry_id: str
    session_id: str

    source_reliability: float = Field(ge=0.0, le=1.0, description="Historical accuracy of this source")
    verification_depth: float = Field(ge=0.0, le=1.0, description="How thoroughly was this belief verified?")
    tag_confidence: float = Field(ge=0.0, le=1.0, description="How appropriate was the epistemic classification?")
    temporal_freshness: float = Field(ge=0.0, le=1.0, description="Age relative to TTL, 1.0 = just verified")
    critique_concordance: float = Field(ge=0.0, le=1.0, description="Did critique agree with classification?")

    composite_score: float = Field(ge=0.0, le=1.0, description="Weighted BQS composite")
    computed_at: datetime = Field(default_factory=lambda: datetime.now(timezone.utc))

    @classmethod
    def compute(
        cls,
        entry_id: str,
        session_id: str,
        source_reliability: float,
        verification_depth: float,
        tag_confidence: float,
        temporal_freshness: float,
        critique_concordance: float,
    ) -> "BQSScore":
        """Weighted composite: the weights reflect my prioritization of source trust."""
        composite = (
            0.25 * source_reliability
            + 0.20 * verification_depth
            + 0.20 * tag_confidence
            + 0.20 * temporal_freshness
            + 0.15 * critique_concordance
        )
        return cls(
            entry_id=entry_id,
            session_id=session_id,
            source_reliability=source_reliability,
            verification_depth=verification_depth,
            tag_confidence=tag_confidence,
            temporal_freshness=temporal_freshness,
            critique_concordance=critique_concordance,
            composite_score=round(min(max(composite, 0.0), 1.0), 4),
        )


# ---------------------------------------------------------------------------
# CPI (Cognitive Pressure Index) Model
# ---------------------------------------------------------------------------

class CPISignals(BaseModel):
    """Raw signal values feeding into CPI computation."""
    model_config = ConfigDict(extra="forbid")

    epistemic_drift_rate: float = Field(ge=0.0, le=1.0)
    source_citation_drop: float = Field(ge=0.0, le=1.0)
    contradiction_tolerance: float = Field(ge=0.0, le=1.0)
    ttl_violation_rate: float = Field(ge=0.0, le=1.0)
    confidence_accuracy_gap: float = Field(ge=0.0, le=1.0)
    decision_velocity: float = Field(ge=0.0, le=1.0)


class CPIScore(BaseModel):
    """
    Cognitive Pressure Index score for a session.
    I'm using 6 behavioral proxy signals to detect when an agent is under pressure.
    """
    model_config = ConfigDict(extra="forbid")

    session_id: str
    signals: CPISignals
    composite_score: float = Field(ge=0.0, le=1.0)
    intervention_level: str = Field(description="GREEN, YELLOW, ORANGE, or RED")
    window_size: int = Field(description="Number of beliefs in the sliding window")
    computed_at: datetime = Field(default_factory=lambda: datetime.now(timezone.utc))

    @classmethod
    def compute(cls, session_id: str, signals: CPISignals, window_size: int) -> "CPIScore":
        """Weighted CPI from 6 signals. Thresholds drive intervention levels."""
        composite = (
            0.25 * signals.epistemic_drift_rate
            + 0.20 * signals.source_citation_drop
            + 0.20 * signals.contradiction_tolerance
            + 0.15 * signals.ttl_violation_rate
            + 0.10 * signals.confidence_accuracy_gap
            + 0.10 * signals.decision_velocity
        )
        composite = round(min(max(composite, 0.0), 1.0), 4)

        if composite < 0.3:
            level = "GREEN"
        elif composite < 0.5:
            level = "YELLOW"
        elif composite < 0.7:
            level = "ORANGE"
        else:
            level = "RED"

        return cls(
            session_id=session_id,
            signals=signals,
            composite_score=composite,
            intervention_level=level,
            window_size=window_size,
        )


# ---------------------------------------------------------------------------
# Conflict Detection Models
# ---------------------------------------------------------------------------

class ConflictType(str, Enum):
    DIRECT_CONTRADICTION = "DIRECT_CONTRADICTION"
    TEMPORAL_CONFLICT = "TEMPORAL_CONFLICT"
    SOURCE_DISAGREEMENT = "SOURCE_DISAGREEMENT"
    RULE_VIOLATION = "RULE_VIOLATION"


class ResolutionStrategy(str, Enum):
    HIGHER_BQS_WINS = "HIGHER_BQS_WINS"
    NEWER_VERIFIED_WINS = "NEWER_VERIFIED_WINS"
    USER_STATED_PRIORITY = "USER_STATED_PRIORITY"
    ESCALATE_TO_HUMAN = "ESCALATE_TO_HUMAN"


class ConflictRecord(BaseModel):
    """
    Tracks a detected conflict between two beliefs.
    I want to capture both the conflict and how it was resolved
    so ORACLE can learn from the pattern.
    """
    model_config = ConfigDict(extra="forbid")

    conflict_id: str = Field(default_factory=lambda: str(uuid.uuid4()))
    session_id: str
    belief_a_id: str
    belief_b_id: str
    conflict_type: ConflictType
    resolution_strategy: ResolutionStrategy
    winner_id: Optional[str] = None
    description: str
    resolved: bool = False
    resolved_at: Optional[datetime] = None
    detected_at: datetime = Field(default_factory=lambda: datetime.now(timezone.utc))


